const gens = { img, audio, video, size, site };

// Returns the Russian page for an English tool entry
export function translateTool(t) {
  const out = t.gen ? gens[t.gen[0]](t, t.gen) : hand[t.slug];
  if (!out) throw new Error('Missing Russian text for ' + t.slug);
  for (const k of ['slug', 'name', 'blurb', 'title', 'desc', 'h1', 'lead', 'intro', 'steps', 'faq']) {
    if (!out[k] || (typeof out[k] === 'string' && out[k].includes('undefined'))) throw new Error(`Russian ${k} missing for ${t.slug}`);
  }
  out.slug = slugify(out.slug);
  return out;
}
